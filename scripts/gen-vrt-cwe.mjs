// Regenerates src/learn/data/vrtCwe.ts from the vendored official VRT snapshot.
// A null leaf mapping falls back to the nearest mapped ancestor (vrt-ruby semantics).
import { createServer } from 'vite';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadOfficialLeaves } from './learn-audit-lib.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const server = await createServer({ root, server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' });
try {
  const leaves = await loadOfficialLeaves();
  const { vrtIndex } = await server.ssrLoadModule('/src/learn/data/vrtIndex.ts');
  const rows = [];
  for (const e of vrtIndex) {
    const p = e.path.startsWith(e.category) ? e.path : `${e.category} › ${e.path}`;
    const cwe = leaves.get(p)?.cwe;
    if (cwe) rows.push(`  ${JSON.stringify(p)}: ${JSON.stringify(cwe)},`);
  }
  await writeFile(path.join(root, 'src/learn/data/vrtCwe.ts'), [
    '// AUTO-GENERATED by scripts/gen-vrt-cwe.mjs from the Bugcrowd VRT → CWE mapping',
    '// (release 2026-07-08, mappings/cwe/cwe.json). Keyed by full VRT path. Do not edit by hand.',
    '// A leaf with a null mapping inherits its nearest mapped ancestor (vrt-ruby semantics).',
    'export const vrtCwe: Record<string, string[]> = {', ...rows, '};', ''].join('\n'));
  console.log(`vrtCwe: ${rows.length} of ${vrtIndex.length} leaves have an official CWE`);
} finally { await server.close(); }
